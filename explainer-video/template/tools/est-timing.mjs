// Estimated narration timing for the storyboard, before the real voice is recorded.
// Writes js/vo-timing.js in the same format the recorded timing will use, so every
// cue in js/scenes/*.js works unchanged once real word timings replace these estimates.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { chapters, tokens } from './script.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const syll = (w) => Math.max(1, (w.replace(/e$/, '').match(/[aeiouy]+/g) || []).length);
const words = [], chaps = [];
let t = 0;
for (const ch of chapters()) {
  chaps.push({ num: ch.num, title: ch.title, t0: +t.toFixed(3) });
  for (const raw of ch.text.split(/\s+/)) {
    const toks = tokens(raw);
    toks.forEach((tk, i) => {
      const d = /^\d/.test(tk) ? 0.45 : 0.09 + 0.135 * syll(tk);
      words.push([tk, +t.toFixed(3), +(t + d).toFixed(3)]);
      t += d + (i < toks.length - 1 ? 0.02 : 0.05);
    });
    if (/[.?!]["]?$/.test(raw)) t += 0.42; else if (/[,:;]$/.test(raw)) t += 0.2;
  }
  chaps[chaps.length - 1].t1 = +t.toFixed(3);
  t += 0.9;                                           // breath between chapters
}
const out = { estimated: true, duration: +(t - 0.9).toFixed(3), chapters: chaps, words };
fs.writeFileSync(path.join(ROOT, 'js/vo-timing.js'), `// Generated by tools/est-timing.mjs: ESTIMATED narration timing (storyboard only).\nwindow.VO_TIMING = ${JSON.stringify(out)};\n`);
console.log(`estimated ${words.length} words, ${out.duration.toFixed(1)} s`, chaps.map((c) => `${c.num}@${c.t0.toFixed(1)}`).join(' '));
